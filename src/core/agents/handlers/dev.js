/**
 * Utility functions
 */
function delay(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

function toPascalCase(str) {
  return str
    .split(/[-_\s]+/)
    .map(word => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join('');
}

