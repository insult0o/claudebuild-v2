/**
 * Write tests
 */
async function writeTests(context) {
  const { task, log, updateStatus, updateProgress, writeFile } = context;
  
  updateStatus('analyzing code to test');
  log(`Writing tests for: ${task.component || 'component'}`);
  
  updateProgress(30);
  await delay(1000);
  
  updateStatus('generating test cases');
  updateProgress(60);
  
  const tests = generateExampleTests(task);
  
  if (task.testFile) {
    await writeFile(task.testFile, tests);
    log(`Tests written to: ${task.testFile}`);
  }
  
  updateProgress(100);
  
  return {
    success: true,
    component: task.component,
    testCases: 5,
    coverage: '85%',
    message: 'Tests created successfully'
  };
}

/**
 * General development task
 */
async function generalDevelopment(context) {
  const { task, log, updateStatus, updateProgress } = context;
  
  log('Executing general development task');
  updateStatus('working');
  
  // Simulate work with progress updates
  for (let i = 0; i <= 100; i += 20) {
    updateProgress(i);
    await delay(1000);
  }
  
  return {
    success: true,
    taskId: task.id,
    message: 'Development task completed'
  };
}

